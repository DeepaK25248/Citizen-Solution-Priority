def update_complaint(complaint_id, status=None, category=None, priority=None,
                      is_fake=None, priority_locked=None, confidence=None,
                      email_sent=None, email_sent_at=None):
    conn = get_conn()
    if status is not None:
        conn.execute("UPDATE complaints SET status = ? WHERE id = ?", (status, complaint_id))
    if category is not None:
        conn.execute("UPDATE complaints SET category = ? WHERE id = ?", (category, complaint_id))
    if priority is not None:
        conn.execute("UPDATE complaints SET priority = ? WHERE id = ?", (priority, complaint_id))
    if is_fake is not None:
        conn.execute("UPDATE complaints SET is_fake = ? WHERE id = ?", (1 if is_fake else 0, complaint_id))
    if priority_locked is not None:
        conn.execute("UPDATE complaints SET priority_locked = ? WHERE id = ?",
                      (1 if priority_locked else 0, complaint_id))
    if confidence is not None:
        conn.execute("UPDATE complaints SET confidence = ? WHERE id = ?", (float(confidence), complaint_id))
    if email_sent is not None:
        conn.execute("UPDATE complaints SET email_sent = ? WHERE id = ?",
                     (1 if email_sent else 0, complaint_id))
    if email_sent_at is not None:
        conn.execute("UPDATE complaints SET email_sent_at = ? WHERE id = ?",
                     (email_sent_at, complaint_id))
    conn.commit()
    conn.close()


