def get_stats():
    conn = get_conn()
    by_category = conn.execute(
        "SELECT category, COUNT(*) as cnt FROM complaints GROUP BY category ORDER BY cnt DESC"
    ).fetchall()
    by_status = conn.execute(
        "SELECT status, COUNT(*) as cnt FROM complaints GROUP BY status"
    ).fetchall()
    by_city = conn.execute(
        "SELECT city, COUNT(*) as cnt FROM complaints WHERE city IS NOT NULL AND city != '' "
        "GROUP BY city ORDER BY cnt DESC"
    ).fetchall()
    total = conn.execute("SELECT COUNT(*) as cnt FROM complaints").fetchone()["cnt"]
    fake = conn.execute("SELECT COUNT(*) as cnt FROM complaints WHERE is_fake = 1").fetchone()["cnt"]
    total_upvotes = conn.execute("SELECT COALESCE(SUM(upvotes), 0) as cnt FROM complaints").fetchone()["cnt"]

    # Priority breakdown uses *effective* priority (accounts for upvote
    # escalation) so this chart matches the badges shown throughout the
    # app, not the raw stored column.
    all_rows = conn.execute("SELECT priority, upvotes, priority_locked FROM complaints").fetchall()
    conn.close()
    priority_counts = {"High": 0, "Medium": 0, "Low": 0}
    for r in all_rows:
        eff = effective_priority(r["priority"], r["upvotes"], bool(r["priority_locked"]))
        priority_counts[eff] = priority_counts.get(eff, 0) + 1
    by_priority = [
        {"priority": p, "cnt": priority_counts[p]}
        for p in ["High", "Medium", "Low"] if priority_counts[p] > 0
    ]

    return {
        "by_category": [dict(r) for r in by_category],
        "by_status": [dict(r) for r in by_status],
        "by_priority": by_priority,
        "by_city": [dict(r) for r in by_city],
        "total": total,
        "fake": fake,
        "total_upvotes": total_upvotes,
    }
