def _perceptual_hash(image_data):
    try:
        with Image.open(BytesIO(image_data)) as image:
            pixels = np.asarray(
                ImageOps.exif_transpose(image).convert("L").resize(
                    (32, 32), Image.Resampling.LANCZOS
                ),
                dtype=np.float32,
            )
    except (OSError, ValueError):
        return None

    positions = np.arange(32)
    frequencies = positions[:, None]
    transform = np.cos(
        np.pi * (2 * positions + 1) * frequencies / (2 * 32)
    )
    transform[0, :] *= 1 / np.sqrt(2)
    transform *= np.sqrt(2 / 32)
    low_frequency = (transform @ pixels @ transform.T)[:8, :8]
    median = np.median(low_frequency.flatten()[1:])
    image_hash = 0
    for coefficient in low_frequency.flat:
        image_hash = (image_hash << 1) | int(coefficient > median)
    return image_hash


class _PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def execute(self, query, parameters=()):
        return self._connection.execute(query.replace("?", "%s"), parameters)

    def executemany(self, query, parameters):
        cursor = self._connection.cursor()
        return cursor.executemany(query.replace("?", "%s"), parameters)

    def commit(self):
        self._connection.commit()

    def close(self):
        self._connection.close()

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self._connection.__exit__(exc_type, exc_value, traceback)


