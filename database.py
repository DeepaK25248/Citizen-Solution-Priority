def init_db():
    conn = get_conn()
    if USE_POSTGRES:
        try:
            _init_postgres_db(conn)
        finally:
            conn.close()
        return

    conn.execute("""
        CREATE TABLE IF NOT EXISTS citizen_users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL COLLATE NOCASE UNIQUE,
            name TEXT NOT NULL,
            email TEXT NOT NULL COLLATE NOCASE UNIQUE,
            password_hash TEXT NOT NULL,
            created_at TEXT NOT NULL,
            city TEXT NOT NULL DEFAULT '',
            area TEXT NOT NULL DEFAULT '',
            ward TEXT NOT NULL DEFAULT '',
            preferred_language TEXT NOT NULL DEFAULT 'en',
            email_notifications INTEGER NOT NULL DEFAULT 1,
            civic_alerts INTEGER NOT NULL DEFAULT 1,
            avatar_path TEXT NOT NULL DEFAULT ''
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS complaints (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            complaint_type TEXT NOT NULL,       -- 'text' or 'image'
            description TEXT,
            image_path TEXT,
            city TEXT,
            location TEXT,
            category TEXT NOT NULL,
            confidence REAL,
            priority TEXT NOT NULL DEFAULT 'Low',      -- High / Medium / Low
            status TEXT NOT NULL DEFAULT 'Pending',   -- Pending / Processing / Solved
            is_fake INTEGER NOT NULL DEFAULT 0,
            upvotes INTEGER NOT NULL DEFAULT 0,
            priority_locked INTEGER NOT NULL DEFAULT 0,
            citizen_name TEXT,
            citizen_email TEXT,
            citizen_phone TEXT,
            sms_opt_in INTEGER NOT NULL DEFAULT 0,
            email_opt_in INTEGER NOT NULL DEFAULT 0,
            email_sent INTEGER NOT NULL DEFAULT 0,
            email_sent_at TEXT,
            created_at TEXT NOT NULL,
            latitude REAL,
            longitude REAL
            ,is_demo INTEGER NOT NULL DEFAULT 0
            ,demo_key TEXT UNIQUE
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS complaint_votes (
            complaint_id INTEGER NOT NULL,
            voter_id TEXT NOT NULL,
            created_at TEXT NOT NULL,
            PRIMARY KEY (complaint_id, voter_id)
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS migrated_complaint_sources (
            source_id TEXT PRIMARY KEY,
            complaint_id INTEGER NOT NULL REFERENCES complaints(id)
        )
    """)
    # Backfill for databases created before these columns existed.
    existing_cols = [row["name"] for row in conn.execute("PRAGMA table_info(complaints)")]
    citizen_cols = [row["name"] for row in conn.execute("PRAGMA table_info(citizen_users)")]
    if "is_demo" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN is_demo INTEGER NOT NULL DEFAULT 0")
    if "demo_key" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN demo_key TEXT")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS complaints_demo_key ON complaints (demo_key)"
    )
    profile_columns = {
        "city": "TEXT NOT NULL DEFAULT ''",
        "area": "TEXT NOT NULL DEFAULT ''",
        "ward": "TEXT NOT NULL DEFAULT ''",
        "preferred_language": "TEXT NOT NULL DEFAULT 'en'",
        "email_notifications": "INTEGER NOT NULL DEFAULT 1",
        "civic_alerts": "INTEGER NOT NULL DEFAULT 1",
        "avatar_path": "TEXT NOT NULL DEFAULT ''",
    }
    for column, definition in profile_columns.items():
        if column not in citizen_cols:
            conn.execute(f"ALTER TABLE citizen_users ADD COLUMN {column} {definition}")
    if "priority" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN priority TEXT NOT NULL DEFAULT 'Low'")
    if "upvotes" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN upvotes INTEGER NOT NULL DEFAULT 0")
    if "priority_locked" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN priority_locked INTEGER NOT NULL DEFAULT 0")
    if "latitude" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN latitude REAL")
    if "longitude" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN longitude REAL")
    if "citizen_phone" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN citizen_phone TEXT")
    if "sms_opt_in" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN sms_opt_in INTEGER NOT NULL DEFAULT 0")
    if "email_opt_in" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN email_opt_in INTEGER NOT NULL DEFAULT 0")
    if "email_sent" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN email_sent INTEGER NOT NULL DEFAULT 0")
    if "email_sent_at" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN email_sent_at TEXT")
    if "translated_description" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN translated_description TEXT")
    if "source_language" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN source_language TEXT NOT NULL DEFAULT 'en'")
    if "citizen_user_id" not in existing_cols:
        conn.execute("ALTER TABLE complaints ADD COLUMN citizen_user_id INTEGER REFERENCES citizen_users(id)")
    for row in conn.execute("SELECT id, confidence FROM complaints WHERE typeof(confidence) = 'blob'"):
        try:
            confidence = struct.unpack("<f", row["confidence"])[0] if len(row["confidence"]) == 4 else float(row["confidence"].decode("ascii"))
        except (UnicodeDecodeError, ValueError, struct.error):
            continue
        if math.isfinite(confidence):
            conn.execute("UPDATE complaints SET confidence = ? WHERE id = ?", (confidence, row["id"]))
    conn.commit()
    conn.close()


