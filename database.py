def merge_migrated_complaints(complaints):
    """Merge redacted source records once, without replacing live complaints."""
    conn = get_conn()
    imported = 0
    skipped = 0
    try:
        with conn:
            for complaint in complaints:
                source_id = complaint["migration_source_id"]
                existing_source = conn.execute(
                    "SELECT complaint_id FROM migrated_complaint_sources WHERE source_id = ?",
                    (source_id,),
                ).fetchone()
                if existing_source:
                    skipped += 1
                    continue

                existing_report = conn.execute("""
                    SELECT id FROM complaints
                    WHERE category = ?
                      AND COALESCE(description, '') = COALESCE(?, '')
                      AND COALESCE(city, '') = COALESCE(?, '')
                      AND COALESCE(location, '') = COALESCE(?, '')
                      AND created_at = ?
                    ORDER BY id
                    LIMIT 1
                """, (
                    complaint["category"],
                    complaint["description"],
                    complaint["city"],
                    complaint["location"],
                    complaint["created_at"],
                )).fetchone()
                if existing_report:
                    conn.execute(
                        "INSERT INTO migrated_complaint_sources (source_id, complaint_id) VALUES (?, ?)",
                        (source_id, existing_report["id"]),
                    )
                    skipped += 1
                    continue

                cursor = conn.execute("""
                    INSERT INTO complaints
                    (complaint_type, description, image_path, city, location,
                     category, confidence, priority, status, is_fake, upvotes,
                     priority_locked, citizen_name, citizen_email, citizen_phone,
                     sms_opt_in, email_opt_in, created_at, latitude, longitude)
                    VALUES (?, ?, NULL, ?, ?, ?, ?, ?, ?, ?, ?, 0, NULL, NULL,
                            NULL, 0, 0, ?, NULL, NULL)
                    RETURNING id
                """, (
                    complaint["complaint_type"],
                    complaint["description"],
                    complaint["city"],
                    complaint["location"],
                    complaint["category"],
                    complaint["confidence"],
                    complaint["priority"],
                    complaint["status"],
                    1 if complaint["is_fake"] else 0,
                    complaint["upvotes"],
                    complaint["created_at"],
                ))
                conn.execute(
                    "INSERT INTO migrated_complaint_sources (source_id, complaint_id) VALUES (?, ?)",
                    (source_id, cursor.fetchone()["id"]),
                )
                imported += 1
    finally:
        conn.close()
    return imported, skipped


def replace_complaints(complaints):
    """Replace all complaints in one transaction, preserving supplied IDs."""
    conn = get_conn()
    try:
        with conn:
            conn.execute("DELETE FROM complaint_votes")
            conn.execute("DELETE FROM migrated_complaint_sources")
            conn.execute("DELETE FROM complaints")
            if not USE_POSTGRES:
                conn.execute("DELETE FROM sqlite_sequence WHERE name = 'complaints'")
            conn.executemany("""
                INSERT INTO complaints
                (id, complaint_type, description, image_path, city, location,
                 category, confidence, priority, status, is_fake, upvotes,
                 priority_locked, citizen_name, citizen_email, citizen_phone,
                 sms_opt_in, email_opt_in, created_at, latitude, longitude)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?, ?, ?, ?, ?, ?, ?, ?)
            """, [(
                complaint["id"], complaint["complaint_type"], complaint["description"],
                complaint["image_path"], complaint["city"], complaint["location"],
                complaint["category"], complaint["confidence"], complaint["priority"],
                complaint["status"], 1 if complaint["is_fake"] else 0,
                complaint["upvotes"], complaint["citizen_name"],
                complaint["citizen_email"], complaint.get("citizen_phone"),
                1 if complaint.get("sms_opt_in") else 0,
                1 if complaint.get("email_opt_in") else 0,
                complaint["created_at"],
                complaint.get("latitude"), complaint.get("longitude"),
            ) for complaint in complaints])
            if USE_POSTGRES:
                conn.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('complaints', 'id'),
                        COALESCE((SELECT MAX(id) FROM complaints), 1),
                        EXISTS(SELECT 1 FROM complaints)
                    )
                """)
    finally:
        conn.close()


def clear_all_complaints():
    """Delete every complaint and reset the next complaint ID to 1."""
    conn = get_conn()
    try:
        with conn:
            rows = conn.execute(
                "SELECT id, image_path FROM complaints"
            ).fetchall()
            conn.execute("DELETE FROM complaint_votes")
            conn.execute("DELETE FROM migrated_complaint_sources")
            conn.execute("DELETE FROM complaints")
            if USE_POSTGRES:
                conn.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('complaints', 'id'),
                        1,
                        false
                    )
                """)
            else:
                conn.execute(
                    "DELETE FROM sqlite_sequence WHERE name = 'complaints'"
                )
            return [
                (row["id"], row["image_path"])
                for row in rows
            ]
    finally:
        conn.close()


def find_similar_complaints(description, city=None, latitude=None, longitude=None,
                            limit=5, category=None, location=None,
                            include_demo=True, image_bytes=None):
    def normalize_text(value):
        folded = unicodedata.normalize("NFKC", value or "").casefold()
        characters = [
            character if unicodedata.category(character)[0] in {"L", "N"} else " "
            for character in folded
        ]
        return " ".join("".join(characters).split())

    stop_words = {
        "a", "an", "and", "are", "at", "be", "been", "by", "for", "from",
        "has", "have", "i", "in", "is", "it", "near", "of", "on",
        "our", "the", "there", "this", "to", "was", "we", "were",
    }
    word_groups = (
        ("waste", "garbage", "rubbish", "trash"),
        ("collect", "collected", "collection", "pickup", "pick", "picked", "picking"),
        ("block", "blocked", "blocking", "choked", "clogged"),
        ("drain", "drainage"),
        ("leak", "leaking", "leaked", "leakage"),
        ("pothole", "potholes"),
        ("light", "lights", "streetlight", "streetlights", "lamp", "lamps"),
        ("overflow", "overflowing", "overflows"),
        ("work", "working", "works", "worked"),
    )
    canonical_words = {
        word: group[0]
        for group in word_groups
        for word in group
    }

    def complaint_words(value):
        return {
            canonical_words.get(word, word)
            for word in normalize_text(value).split()
            if word not in stop_words and len(word) > 1
        }

    normalized = normalize_text(description)
    submitted_words = complaint_words(description)
    normalized_location = normalize_text(location)
    submitted_image_hash = _perceptual_hash(image_bytes) if image_bytes else None
    has_coordinates = latitude is not None and longitude is not None
    if (
        not (city or normalized_location or has_coordinates)
        or (
            not normalized
            and not (normalized_location and category)
            and not (submitted_image_hash is not None and category)
        )
    ):
        return []

    conn = get_conn()
    rows = conn.execute("SELECT * FROM complaints").fetchall()
    conn.close()

    matches = []
    for row in rows:
        if row["is_demo"] and not include_demo:
            continue

        existing_descriptions = {
            normalize_text(row["description"]),
            normalize_text(row["translated_description"]),
        } - {""}

        distance_m = None
        if has_coordinates and row["latitude"] is not None and row["longitude"] is not None:
            lat1, lat2 = math.radians(latitude), math.radians(row["latitude"])
            delta_lat = lat2 - lat1
            delta_lon = math.radians(row["longitude"] - longitude)
            value = math.sin(delta_lat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(delta_lon / 2) ** 2
            distance_m = 6_371_000 * 2 * math.atan2(math.sqrt(value), math.sqrt(max(0, 1 - value)))

        same_ward = bool(
            city
            and row["city"]
            and normalize_text(city) == normalize_text(row["city"])
        )
        existing_location = normalize_text(row["location"])
        same_location = bool(normalized_location and existing_location == normalized_location)
        location_similarity = SequenceMatcher(
            None, normalized_location, existing_location
        ).ratio() if normalized_location and existing_location else 0
        submitted_location_words = complaint_words(normalized_location)
        existing_location_words = complaint_words(existing_location)
        shared_location_words = submitted_location_words & existing_location_words
        location_overlap = (
            len(shared_location_words) / min(len(submitted_location_words), len(existing_location_words))
            if submitted_location_words and existing_location_words
            else 0
        )
        matching_location = bool(
            same_location
            or location_similarity >= 0.6
            or location_overlap >= 0.5
        )
        compatible_location = bool(
            not normalized_location
            or not existing_location
            or matching_location
        )
        nearby_coordinates = bool(distance_m is not None and distance_m <= 100)
        location_in_same_area = bool(
            matching_location
            and (
                not city
                or not row["city"]
                or normalize_text(city) == normalize_text(row["city"])
            )
        )
        same_area = same_ward or location_in_same_area or nearby_coordinates
        same_category = bool(category and row["category"] == category)
        same_image = False
        image_path = row["image_path"] or ""
        if (
            submitted_image_hash is not None
            and same_category
            and same_area
            and image_path.startswith("uploads/")
            and os.path.basename(image_path) == image_path[len("uploads/"):]
        ):
            upload_dir = os.environ.get(
                "CITYSOLUTION_UPLOAD_DIR",
                os.path.join(os.path.dirname(os.path.abspath(__file__)), "static", "uploads"),
            )
            try:
                with open(os.path.join(upload_dir, os.path.basename(image_path)), "rb") as image_file:
                    existing_image_hash = _perceptual_hash(image_file.read())
                same_image = (
                    existing_image_hash is not None
                    and (submitted_image_hash ^ existing_image_hash).bit_count() <= 8
                )
            except FileNotFoundError:
                logger.warning("Complaint %s references a missing upload: %s", row["id"], image_path)

        description_score = 0
        enough_description_match = False
        for existing_text in existing_descriptions:
            existing_words = complaint_words(existing_text)
            shared_words = submitted_words & existing_words
            overlap_similarity = (
                len(shared_words) / min(len(submitted_words), len(existing_words))
                if submitted_words and existing_words
                else 0
            )
            text_similarity = SequenceMatcher(
                None, normalized, existing_text
            ).ratio()
            description_score = max(
                description_score,
                text_similarity * 100,
                overlap_similarity * 100,
            )
            enough_description_match = enough_description_match or bool(
                normalized == existing_text
                or text_similarity >= 0.68
                or (len(shared_words) >= 2 and overlap_similarity >= 0.5)
                or (
                    category == row["category"]
                    and len(shared_words) >= 1
                    and min(len(submitted_words), len(existing_words)) <= 4
                    and max(map(len, shared_words)) >= 4
                )
            )

        same_category_and_location = bool(
            same_category and matching_location
        )
        same_complaint = bool(
            same_area
            and compatible_location
            and (
                same_category_and_location
                or same_image
                or (same_category and enough_description_match)
                or (
                    not same_category
                    and normalized
                    and description_score >= 82
                    and enough_description_match
                )
            )
        )
        if same_complaint:
            matches.append({
                "id": row["id"],
                "description": row["description"],
                "city": row["city"],
                "location": row["location"],
                "category": row["category"],
                "status": row["status"],
                "created_at": row["created_at"],
                "upvotes": row["upvotes"],
                "similarity": round(description_score),
                "distance_m": round(distance_m) if distance_m is not None else None,
            })

    matches.sort(key=lambda match: (
        -(
            match["similarity"]
            + (100 if normalized_location and normalize_text(match["location"]) == normalized_location else 0)
            + (20 if city and match["city"] and city.casefold() == match["city"].casefold() else 0)
            + (10 if category and match["category"] == category else 0)
            + (20 if match["distance_m"] is not None and match["distance_m"] <= 100 else 0)
        ),
        match["id"],
    ))
    return matches[:limit]


